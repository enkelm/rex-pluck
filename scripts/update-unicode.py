#!/usr/bin/env python3
"""Regenerate vendored Unicode 17 data; optional maintenance tool, never used at runtime/tests."""
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://www.unicode.org/Public/17.0.0/ucd/"


def fetch(path):
    with urlopen(BASE + path, timeout=60) as response:
        return response.read().decode("utf-8")


def merge(rows):
    result = []
    for first, last, value in sorted(rows):
        if result and result[-1][1] + 1 == first and result[-1][2] == value:
            result[-1] = (result[-1][0], last, value)
        else:
            result.append((first, last, value))
    return result


def properties(text, name=None):
    rows = []
    for line in text.splitlines():
        fields = [part.strip() for part in line.partition("#")[0].split(";")]
        if len(fields) < 2 or not fields[0] or name and fields[1] != name:
            continue
        bounds = fields[0].split("..")
        rows.append((int(bounds[0], 16), int(bounds[-1], 16), fields[2] if name == "InCB" else fields[1]))
    return merge(rows)


categories = {"L": [], "N": [], "M": []}
start = None
for line in fetch("UnicodeData.txt").splitlines():
    fields = line.split(";")
    cp, name, category = int(fields[0], 16), fields[1], fields[2][0]
    if name.endswith(", First>"):
        start = cp
    elif name.endswith(", Last>"):
        if category in categories:
            categories[category].append((start, cp, category))
        start = None
    elif category in categories:
        categories[category].append((cp, cp, category))
graphemes = properties(fetch("auxiliary/GraphemeBreakProperty.txt"))
indic = properties(fetch("DerivedCoreProperties.txt"), "InCB")
emoji = properties(fetch("emoji/emoji-data.txt"), "Extended_Pictographic")
tables = {"letter": merge(categories["L"]), "number": merge(categories["N"]), "mark": merge(categories["M"]),
          "extended_pictographic": emoji, "regional_indicator": [r for r in graphemes if r[2] == "Regional_Indicator"]}
# ECMAScript \s, used by the original recognizer, differs from Unicode White_Space at NEL/BOM.
tables["white_space"] = [(a, b, "space") for a, b in [(9, 13), (32, 32), (160, 160), (5760, 5760),
    (8192, 8202), (8232, 8233), (8239, 8239), (8287, 8287), (12288, 12288), (65279, 65279)]]
output = ["-- Generated by scripts/update-unicode.py from Unicode 17.0.0; see LICENSE.unicode.", "local M = {}", "local properties = {"]
for key, rows in tables.items():
    values = [f"0x{x:x}" for first, last, _ in rows for x in (first, last)]
    output.append(f"  {key} = {{")
    output.extend("    " + ", ".join(values[i:i + 12]) + "," for i in range(0, len(values), 12))
    output.append("  },")
output.append("}")
for key, rows in [("grapheme", graphemes), ("indic", indic)]:
    output.append(f"local {key} = {{")
    output.extend(f'  {{ 0x{first:x}, 0x{last:x}, "{value}" }},' for first, last, value in rows)
    output.append("}")
output.append('''local function contains(ranges, cp)
  local low, high = 1, #ranges / 2
  while low <= high do
    local middle = math.floor((low + high) / 2)
    local first, last = ranges[middle * 2 - 1], ranges[middle * 2]
    if cp < first then high = middle - 1 elseif cp > last then low = middle + 1 else return true end
  end
  return false
end
local function classify(ranges, cp)
  local low, high = 1, #ranges
  while low <= high do
    local middle = math.floor((low + high) / 2)
    local row = ranges[middle]
    if cp < row[1] then high = middle - 1 elseif cp > row[2] then low = middle + 1 else return row[3] end
  end
  return "Other"
end''')
for key in tables:
    output.append(f"function M.is_{key}(cp) return contains(properties.{key}, cp) end")
output.extend(["function M.grapheme(cp) return classify(grapheme, cp) end", "function M.indic(cp) return classify(indic, cp) end", "return M", ""])
(ROOT / "pluck/unicode.lua").write_text("\n".join(output))
data = ROOT / "tests/data"
data.mkdir(exist_ok=True)
(data / "GraphemeBreakTest.txt").write_text("\n".join(line.rstrip() for line in fetch("auxiliary/GraphemeBreakTest.txt").splitlines()) + "\n")
with urlopen("https://www.unicode.org/license.txt", timeout=60) as response:
    (ROOT / "LICENSE.unicode").write_bytes(response.read())
print("Updated Unicode 17 tables, official grapheme vectors, and Unicode data license.")
